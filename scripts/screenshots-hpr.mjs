import { chromium } from '@playwright/test';
const exe = process.env.PW_CHROMIUM || '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const b = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const out = process.argv[2] || 'screenshots';
const base = process.argv[3] || 'http://localhost:4173';
const logs = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', e => logs.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') logs.push(m.text()); });
const focused = (id) => p.waitForFunction((i) => { const s = window.__SINOR__.state(); return s.selectedId === i && s.phase === 'focused'; }, id, { timeout: 30000 });
const status = (t) => p.waitForFunction((x) => document.querySelector('[data-testid=hpr-status]')?.textContent === x, t, { timeout: 60000 });
await p.goto(base + '/?intro=0&quality=medium');
await p.waitForFunction(() => !!window.__SINOR__, null, { timeout: 45000 }); await p.waitForTimeout(2000);
await p.click('[data-testid=tree-deployment-001]'); await focused('deployment-001'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/30-hpr-7950-parked.png` });
await p.click('[data-testid=mode-xray]'); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/31-hpr-7950-xray.png` });
await p.click('[data-testid=action-explode]'); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/32-hpr-7950-exploded.png` });
await p.click('[data-testid=action-explode]');
await p.click('[data-testid=mode-hybrid]');
await p.selectOption('[data-testid=hpr-speed]', '20');
await p.click('[data-testid=hpr-valve-open]'); await status('READY TO DEPLOY');
await p.click('[data-testid=hpr-deploy]'); await status('DEPLOYED');
await p.click('[data-testid=hpr-signals]');
await p.click('[data-testid=tree-hpr-001]'); await focused('hpr-001'); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/33-hpt5000-deployed.png` });
await p.click('[data-testid=reset-overview]'); await p.waitForTimeout(2000);
await p.click('[data-testid=mode-xray]'); await p.waitForTimeout(1000);
await p.screenshot({ path: `${out}/34-hpr-overview-xray.png` });
console.log('errors:', JSON.stringify(logs));
await b.close();
