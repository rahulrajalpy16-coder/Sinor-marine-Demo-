import { chromium } from '@playwright/test';
const exe = process.env.PW_CHROMIUM || '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const b = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const out = process.argv[2] || 'shots';
const base = process.argv[3] || 'http://localhost:4173';
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
p.on('pageerror', e => logs.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') logs.push(m.text()); });
const ready = () => p.waitForFunction(() => !!window.__SINOR__, null, { timeout: 45000 });
const focused = (id) => p.waitForFunction((i) => { const s = window.__SINOR__.state(); return s.selectedId === i && s.phase === 'focused'; }, id, { timeout: 30000 });
await p.goto(base + '/'); await ready(); await p.waitForTimeout(2600);
await p.screenshot({ path: `${out}/00-intro-reveal.png` });
if (await p.locator('[data-testid=skip-intro]').count()) await p.click('[data-testid=skip-intro]', { timeout: 3000 }).catch(() => {}); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/01-overview-hybrid.png` });
for (const m of ['realistic','blueprint','xray']) { await p.click(`[data-testid=mode-${m}]`); await p.waitForTimeout(1500); await p.screenshot({ path: `${out}/02-mode-${m}.png` }); }
await p.click('[data-testid=mode-hybrid]');
await p.click('[data-testid=tree-bow-thruster-001]'); await focused('bow-thruster-001');
await p.click('[data-testid=thruster-start]'); await p.waitForTimeout(4500);
await p.fill('[data-testid=thrust-input]', '80'); await p.press('[data-testid=thrust-input]', 'Enter'); await p.waitForTimeout(3500);
await p.screenshot({ path: `${out}/03-bow-thruster-running.png` });
await p.click('[data-testid=action-explode]'); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/04-bow-thruster-exploded.png` });
await p.click('[data-testid=thruster-reset]');
await p.click('[data-testid=tree-dp-console-001]'); await focused('dp-console-001'); await p.click('[data-testid=action-inspect]'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/05-dp-console.png` });
await p.click('[data-testid=tree-hpr-001]'); await focused('hpr-001');
await p.click('[data-testid=hpr-signals]'); await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/06-hpr-signals.png` });
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
await m.goto(base + '/?intro=0'); await m.waitForFunction(() => !!window.__SINOR__, null, { timeout: 45000 }); await m.waitForTimeout(2500);
await m.screenshot({ path: `${out}/07-mobile.png` });
console.log('errors:', JSON.stringify(logs));
await b.close();
